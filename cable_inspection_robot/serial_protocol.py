# -*- coding: utf-8 -*-
"""WHEELTEC C30D 底层主控板串口协议封装模块。

本模块定义了机器人主控端与 WHEELTEC C30D 底盘控制器之间的串口通信帧格式，
负责将左右轮目标速度编码为字节帧发送，以及解析底盘返回的左右轮实际速度。

通信帧格式（共 7 字节）：

    +--------+--------+-------------+-------------+------------+
    | 帧头 1 | 帧头 2 | 左轮速度    | 右轮速度    | 校验和     |
    | 0xAA   | 0x55   | int16 (LE)  | int16 (LE)  | uint8      |
    +--------+--------+-------------+-------------+------------+
    | 1 B    | 1 B    | 2 B         | 2 B         | 1 B        |
    +--------+--------+-------------+-------------+------------+

帧字段说明：
    - 帧头：固定为 0xAA 0x55，用于接收端帧同步与定位。
    - 左轮速度：有符号 16 位整数（小端序），单位 mm/s。
    - 右轮速度：有符号 16 位整数（小端序），单位 mm/s。
    - 校验和：前 6 字节按字节累加后的低 8 位。

设计说明：
    - 速度单位在传输时使用 mm/s 而非 m/s，可提高小速度下的传输精度。
    - int16 表示范围为 [-32768, 32767] mm/s，约 [-32.768, 32.767] m/s，
      对于本机器人底盘完全足够。
    - 若底层固件协议不同，只需替换本文件，不影响上层 ROS2/TROS 节点逻辑。
"""

# 启用类型注解的未来导入，支持 tuple[float, float] | None 等现代类型写法
from __future__ import annotations

# 导入 struct 模块，用于 Python 基本数据类型与字节序列之间的打包/解包
import struct


# 定义固定帧头为两个字节的 bytes 对象，用于标识一帧数据的起始位置
# 0xAA 0x55 是常见的自定义串口协议帧头，出现概率低，便于帧同步
HEADER = b"\xAA\x55"


def clamp_mm_s(value: float) -> int:
    """将米/秒（m/s）转换为毫米/秒（mm/s），并限制在 int16 安全范围内。

    转换原因：
        C30D 串口帧使用 16 位有符号整数表示轮速，单位为 mm/s。
        将 m/s 放大 1000 倍后取整，可保留毫米级速度分辨率。

    限幅原因：
        int16 的表示范围为 [-32768, 32767]，超出该范围会导致数据溢出，
        因此需要对转换后的 mm/s 值进行裁剪。

    Args:
        value: 轮速，单位 m/s。正值表示前进方向，负值表示后退方向。

    Returns:
        限制后的整数 mm/s 值，范围 [-32768, 32767]。
    """

    # 将 m/s 放大 1000 倍转换为 mm/s，并四舍五入为整数
    mm_s = int(round(value * 1000.0))

    # 使用 max/min 将结果限制在 int16 范围内
    # 先与 -32768 取最大值，防止下溢；再与 32767 取最小值，防止上溢
    return max(-32768, min(32767, mm_s))


def build_speed_frame(left_m_s: float, right_m_s: float) -> bytes:
    """构造左右轮目标速度控制帧。

    构造流程：
        1. 将左右轮速度从 m/s 转换为 mm/s 并限幅。
        2. 使用小端序将两个 int16 速度值打包为 4 字节 payload。
        3. 在 payload 前追加 2 字节帧头。
        4. 计算前 6 字节的累加和低 8 位作为校验和。
        5. 追加校验和字节，返回完整 7 字节帧。

    Args:
        left_m_s: 左轮目标线速度，单位 m/s。
        right_m_s: 右轮目标线速度，单位 m/s。

    Returns:
        完整的 7 字节控制帧，可直接通过串口发送给 C30D 控制器。
    """

    # 使用 struct.pack 按照小端序（<）打包两个 short（h，即 int16）
    # 先调用 clamp_mm_s 将 m/s 转换为安全范围内的 mm/s 整数
    payload = struct.pack("<hh", clamp_mm_s(left_m_s), clamp_mm_s(right_m_s))

    # 将固定帧头与有效载荷拼接，形成帧头+数据的前 6 字节
    raw = HEADER + payload

    # 计算校验和：对前 6 字节逐字节求和，取低 8 位（与 0xFF 按位与）
    checksum = sum(raw) & 0xFF

    # 将校验和作为单字节追加到帧末尾，返回完整 7 字节帧
    return raw + bytes([checksum])


def parse_wheel_feedback(frame: bytes) -> tuple[float, float] | None:
    """解析底盘返回的左右轮速度反馈帧。

    解析流程：
        1. 检查帧长度是否至少为 7 字节。
        2. 检查前 2 字节是否匹配固定帧头。
        3. 重新计算前 6 字节的校验和，并与第 7 字节比较。
        4. 若校验通过，解包中间 4 字节为两个 int16（小端序）。
        5. 将 mm/s 转换回 m/s 后返回。

    Args:
        frame: 从串口读取到的原始字节序列，可能包含不完整或错误数据。

    Returns:
        若校验通过，返回 (left_m_s, right_m_s) 两个浮点数；
        若长度不足、帧头不匹配或校验失败，返回 None。
    """

    # 第一步：基本长度校验
    # 完整帧需要 7 字节，若接收到的数据不足 7 字节则无法解析
    if len(frame) < 7:
        return None

    # 第二步：帧头校验
    # 检查帧的前 2 字节是否与预定义帧头 0xAA 0x55 一致
    # 不一致说明不是本协议帧或数据未对齐
    if frame[:2] != HEADER:
        return None

    # 第三步：校验和校验
    # 重新计算前 6 字节的累加和低 8 位，与帧中第 7 字节（索引 6）比较
    # 不一致说明传输过程中出现误码
    if (sum(frame[:6]) & 0xFF) != frame[6]:
        return None

    # 第四步：解包速度值
    # 从第 3 字节到第 6 字节（索引 2:6）为两个 int16，使用小端序解包
    left_mm_s, right_mm_s = struct.unpack("<hh", frame[2:6])

    # 第五步：单位转换
    # 将 mm/s 除以 1000 转换回 m/s，返回浮点数元组
    return left_mm_s / 1000.0, right_mm_s / 1000.0
